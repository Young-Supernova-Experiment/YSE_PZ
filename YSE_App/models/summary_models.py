"""AI summaries (#294: #295 field + history, #296 summariser service, #297 embeddings + search).

``Transient.summary`` holds the current text; every version that was ever
current, whether the summariser wrote it or a person edited it, is a
:class:`TransientSummaryHistory` row with its provenance (source, provider,
model, prompt version, hash of the inputs, the service run), so an edit never
loses a previous version. :class:`TransientSummaryEmbedding` is the one vector
per transient that ``/summary_search/`` ranks by cosine similarity; it stores
the embedder's name so vectors of different models are never compared.
:class:`TransientSummaryPreference` is the per-user opt-in for generating
summaries with an LLM (the group side of the opt-in is the ``groups`` field of
the ``ai_summary`` ``ExternalService`` row).

The shape (a summary column, a history of versions with their origin, one
embedding per object, natural-language search over the embeddings) follows
SkyPortal's summary and summary-search design (BSD-3-Clause) in spirit; no
code is copied from that project.
"""

from __future__ import annotations

import struct
from typing import List, Sequence

from auditlog.registry import auditlog
from django.contrib.auth.models import User
from django.db import models

from YSE_App.models.base import BaseModel
from YSE_App.models.external_service_models import ExternalServiceRun
from YSE_App.models.transient_models import Transient

SOURCE_AI = "ai"
SOURCE_HUMAN = "human"
SOURCE_CHOICES = ((SOURCE_AI, "Generated by the summariser"), (SOURCE_HUMAN, "Written or edited by a person"))

# Django permission (YSE_App.can_edit_summary): lets a user edit summaries of transients
# they can see even when SUMMARY_EDIT_STAFF_ONLY is on.
EDIT_PERMISSION = "can_edit_summary"


def first_line(text) -> str:
    """The first non-empty line of ``text`` (for tooltips and table cells)."""
    for line in (text or "").splitlines():
        if line.strip():
            return line.strip()
    return ""


class TransientSummaryHistory(BaseModel):
    """One version of a transient's summary. ``created_by`` is the editor, or the user who requested the run."""

    transient = models.ForeignKey(Transient, on_delete=models.CASCADE, related_name="summary_history")
    text = models.TextField()
    source = models.CharField(max_length=8, choices=SOURCE_CHOICES, default=SOURCE_HUMAN, db_index=True)
    provider = models.CharField(max_length=32, blank=True, default="",
                                help_text="LLM backend that wrote this version (template, openai, anthropic); blank for a human edit.")
    model_name = models.CharField(max_length=120, blank=True, default="",
                                  help_text="The model that wrote this version (blank for a human edit).")
    prompt_version = models.CharField(max_length=16, blank=True, default="")
    inputs_hash = models.CharField(max_length=64, blank=True, default="",
                                   help_text="sha256 of the gathered context the prompt was built from.")
    run = models.ForeignKey(ExternalServiceRun, null=True, blank=True, on_delete=models.SET_NULL,
                            related_name="summary_versions")
    is_current = models.BooleanField(default=False, db_index=True)

    class Meta:
        ordering = ("-created_date", "-id")
        permissions = ((EDIT_PERMISSION, "Can edit transient summaries"),)
        verbose_name = "transient summary version"
        verbose_name_plural = "transient summary versions"

    def __str__(self):
        return "%s summary v%s (%s)" % (self.transient.name, self.pk, self.source)

    @property
    def is_ai(self) -> bool:
        return self.source == SOURCE_AI

    @property
    def author(self) -> str:
        """Who to show as the author: the model for a generated version, else the editor."""
        if self.source == SOURCE_AI:
            return self.model_name or self.provider or "summariser"
        return self.created_by.username if self.created_by_id else ""

    @property
    def first_line(self) -> str:
        return first_line(self.text)


def pack_vector(values: Sequence[float]) -> bytes:
    """float32 little-endian bytes for ``values`` (the on-disk form of an embedding)."""
    values = list(values)
    return struct.pack("<%df" % len(values), *[float(v) for v in values])


def unpack_vector(blob) -> List[float]:
    blob = bytes(blob or b"")
    n = len(blob) // 4
    return list(struct.unpack("<%df" % n, blob[: n * 4])) if n else []


class TransientSummaryEmbedding(models.Model):
    """The embedding of the transient's current summary (one row per transient)."""

    transient = models.OneToOneField(Transient, on_delete=models.CASCADE, related_name="summary_embedding")
    vector = models.BinaryField(blank=True, default=bytes,
                                help_text="float32 little-endian, L2-normalised (pack_vector / unpack_vector).")
    dim = models.PositiveIntegerField(default=0)
    model_name = models.CharField(max_length=120, db_index=True,
                                  help_text="Embedding model; vectors of different models are never compared.")
    text_hash = models.CharField(max_length=64, blank=True, default="",
                                 help_text="sha256 of the summary text the vector was computed from.")
    created_date = models.DateTimeField(auto_now_add=True)
    modified_date = models.DateTimeField(auto_now=True)

    class Meta:
        verbose_name = "transient summary embedding"

    def __str__(self):
        return "embedding of %s (%s, %d)" % (self.transient.name, self.model_name, self.dim)

    @property
    def values(self) -> List[float]:
        return unpack_vector(self.vector)


class TransientSummaryPreference(models.Model):
    """Per-user opt-in to LLM-generated summaries (#296). Absent row = not opted in."""

    user = models.OneToOneField(User, on_delete=models.CASCADE, related_name="summary_preference")
    ai_enabled = models.BooleanField(default=False, help_text="Show the Generate button and run the summariser for me.")
    created_date = models.DateTimeField(auto_now_add=True)
    modified_date = models.DateTimeField(auto_now=True)

    class Meta:
        verbose_name = "transient summary preference"

    def __str__(self):
        return "%s: AI summaries %s" % (self.user.username, "on" if self.ai_enabled else "off")

    @classmethod
    def enabled_for(cls, user) -> bool:
        if user is None or not getattr(user, "is_authenticated", False):
            return False
        return cls.objects.filter(user=user, ai_enabled=True).exists()


auditlog.register(TransientSummaryHistory)
